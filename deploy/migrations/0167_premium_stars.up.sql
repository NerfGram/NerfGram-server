-- Telegram Premium purchased with the local Stars ledger.
--
-- The plan version and all monetary/duration fields are copied into each
-- payment intent. Checkout therefore never trusts a price supplied by a
-- client and never changes an already issued form after a catalog edit.

ALTER TABLE public.users
    ADD COLUMN premium_updated_at timestamp with time zone;

ALTER TABLE public.account_settings
    ADD COLUMN disallow_unlimited_stargifts boolean DEFAULT false NOT NULL,
    ADD COLUMN disallow_limited_stargifts boolean DEFAULT false NOT NULL,
    ADD COLUMN disallow_unique_stargifts boolean DEFAULT false NOT NULL,
    ADD COLUMN disallow_premium_gifts boolean DEFAULT false NOT NULL,
    ADD COLUMN disallow_stargifts_from_channels boolean DEFAULT false NOT NULL;

CREATE TABLE public.premium_plans (
    months integer NOT NULL,
    duration_days integer NOT NULL,
    amount_stars bigint NOT NULL,
    enabled boolean DEFAULT true NOT NULL,
    sort_order integer DEFAULT 0 NOT NULL,
    label text NOT NULL,
    version bigint DEFAULT 1 NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT premium_plans_pkey PRIMARY KEY (months),
    CONSTRAINT premium_plans_months_valid CHECK (months > 0 AND months <= 120),
    CONSTRAINT premium_plans_duration_valid CHECK (duration_days > 0 AND duration_days <= 36500),
    CONSTRAINT premium_plans_amount_valid CHECK (amount_stars > 0 AND amount_stars <= 1000000000000000),
    CONSTRAINT premium_plans_version_positive CHECK (version > 0),
    CONSTRAINT premium_plans_label_nonempty CHECK (label <> '')
);

